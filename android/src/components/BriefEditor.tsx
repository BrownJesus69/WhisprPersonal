import { useRef, useState } from 'react';
import { Text, TextInput } from 'react-native';
import type { BriefDraft } from '@/lib/ai/types';
import { providerName } from '@/lib/ai/messages';
import { typography, spacing, useTheme } from '@/theme';
import { Button } from './Button';
import { Card } from './Card';
import { Banner } from './Banner';

export function BriefEditor({ draft, persist, save, discard }: {
  draft: BriefDraft; persist: (draft: BriefDraft) => Promise<void>;
  save: (draft: BriefDraft) => Promise<void>; discard: () => Promise<void>;
}) {
  const [text, setText] = useState(draft.edited_text), [busy, setBusy] = useState(false), [error, setError] = useState('');
  const lane = useRef(Promise.resolve());
  const t = useTheme();
  const current = (value: string) => ({ ...draft, edited_text: value, updated_at: new Date().toISOString() });
  const action = (work: () => Promise<void>) => {
    setBusy(true); setError('');
    void lane.current.then(work).catch(() => setError('Could not save this change. Your draft stays on this phone.')).finally(() => setBusy(false));
  };
  return <Card>
    <Text style={{ ...typography.label, color: t.primary }}>Generated by {providerName(draft.provider)}{draft.model ? ` · ${draft.model}` : ''}</Text>
    <Banner message="AI-generated — check it against the transcript" />
    {!!draft.incomplete && <Banner message="Generated from an incomplete transcript. Some parts may be missing." />}
    {draft.warning === 'unstructured_output' && <Banner message="The output could not be organized into sections. Review the text carefully." />}
    <TextInput accessibilityLabel="Brief draft" multiline maxLength={100000} value={text} editable={!busy}
      style={{ ...typography.body, color: t.text, backgroundColor: t.surface, borderColor: t.border, borderWidth: 1, borderRadius: spacing.sm, padding: spacing.sm, minHeight: 240, textAlignVertical: 'top' }}
      onChangeText={value => {
        setText(value);
        lane.current = lane.current.catch(() => {}).then(() => persist(current(value)));
        void lane.current.catch(() => setError('Could not store edits on this phone. Try saving again.'));
      }} />
    {error && <Banner error message={error} />}
    <Button label="Save" disabled={!text.trim()} loading={busy} onPress={() => action(() => save(current(text)))} />
    <Button secondary label="Discard" disabled={busy} onPress={() => action(discard)} />
  </Card>;
}
