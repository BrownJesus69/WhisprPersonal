test('tabs switch explicitly and polished rows show the label and raw fallback', async () => {
  const select = jest.fn();
  const tabs = await render(<TranscriptTabs selected="raw" onSelect={select} />);
  await fireEvent.press(tabs.getByLabelText('Polished')); expect(select).toHaveBeenCalledWith('polished');
  await tabs.rerender(<TranscriptTabs selected="polished" onSelect={select} />);
  expect(tabs.getByText('AI-cleaned text. Your raw transcript is unchanged.')).toBeTruthy();
  const model = withFinal(withFinal(initialTranscript(),finalData()),finalData({ sequence: 1, raw_text: 'Fallback raw' }));
  const view = await render(<TranscriptList model={model} chunkStarts={{}} polished stored={[{ ...transcriptRow(session().id,finalData()), polished_text: 'Cleaned words' }]} />);
  expect(view.getByText('Cleaned words')).toBeTruthy(); expect(view.getByText('Fallback raw')).toBeTruthy(); expect(view.getByText('Not cleaned')).toBeTruthy();
  await view.rerender(<TranscriptList model={model} chunkStarts={{}} />);
  expect(view.getByText('original')).toBeTruthy(); expect(view.queryByText('Cleaned words')).toBeNull();
});
