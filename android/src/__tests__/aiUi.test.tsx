  const view = await render(<BriefEditor draft={draft({ incomplete: 1, warning: 'unstructured_output' })} persist={persist} save={save} discard={discard} />);
  expect(view.getByText('Generated by Groq · test model')).toBeTruthy(); expect(view.getByText('AI-generated — check it against the transcript')).toBeTruthy();
